"""Export the Stage-1 GPU ablation study into thesis-ready LaTeX tables + figures.

Reads the sweep outputs written by ``run_stage1_sweep.py``:
    <outdir>/manifest.jsonl   one line per run: config + best_/final_ metrics
    <outdir>/curves.csv       per-checkpoint metric vs timesteps (for figures)

and writes drop-in artifacts to ``<outdir>/thesis_export/``:
    reward_ablation_forward.tex / reward_ablation_reverse.tex
    algorithm_comparison_forward.tex / algorithm_comparison_reverse.tex
    forward_reward_ablation.pdf / reverse_reward_ablation.pdf   (learning curves)
    _README.txt   the \\input lines / copy commands to pull these into the thesis

Design notes
------------
* Completion is a **fraction in [0,1]** in the study and is rendered as a percent.
  It comes from the env's threshold-based success (reach past 0.85*world_width),
  captured *before* auto-reset -- i.e. NOT the exact-100% artifact that zeroed the
  old e2e_rl tables. So these numbers are already correct; we only format them.
* Every cell is a mean +/- 95% CI over seeds (the multi-seed "Statistical Rigor").
* We report each run's **best checkpoint** (best_*), matching the ablation's design.
* This lives in the CuPy copy and writes only inside it -- it never edits the thesis
  LaTeX. Import is a one-line \\input (or copy) shown in the generated _README.txt.

    python scripts/export_thesis_results.py --outdir results_stage1_v2
"""

import os
import csv
import json
import math
import argparse
from collections import defaultdict

import numpy as np

# ----- display names -------------------------------------------------------------
ALGO_NAME = {"td3": "TD3", "ppo": "PPO", "ppo_disc": "PPO (discrete)", "dqn": "DQN",
             "sac": "SAC"}
REWARD_NAME = {"dense": "Dense", "tractor_focus": "Tractor-focus", "no_hitch": "No-hitch",
               "multiplicative": "Multiplicative", "guided": "Guided (PP)"}
# canonical ordering so tables read consistently regardless of run order
ALGO_ORDER = ["td3", "ppo", "dqn", "ppo_disc", "sac"]
REWARD_ORDER = ["dense", "tractor_focus", "no_hitch", "multiplicative", "guided"]


def ci95(xs):
    xs = [x for x in xs if x == x]
    if len(xs) < 2:
        return 0.0
    return 1.96 * float(np.std(xs, ddof=1)) / math.sqrt(len(xs))


def load_runs(outdir):
    """Return completed run records from the manifest (skips errors / in-flight)."""
    path = os.path.join(outdir, "manifest.jsonl")
    runs = []
    with open(path) as f:
        for line in f:
            try:
                rec = json.loads(line)
            except Exception:
                continue
            if "error" in rec or "best_completion" not in rec:
                continue
            runs.append(rec)
    return runs


def aggregate(runs, keys):
    """Group runs by the tuple of `keys` -> dict of metric -> (mean, ci95, n)."""
    groups = defaultdict(list)
    for r in runs:
        groups[tuple(r[k] for k in keys)].append(r)
    out = {}
    for key, recs in groups.items():
        agg = {"n_seeds": len(recs)}
        for m in ["completion", "trailer_cte", "max_hitch", "jackknife", "ep_return"]:
            vals = [r[f"best_{m}"] for r in recs if f"best_{m}" in r]
            agg[m] = (float(np.mean(vals)), ci95(vals)) if vals else (float("nan"), 0.0)
        # deployment/reliability columns for completion: best-seed (max, "deploy the best")
        # and robustness (# seeds >= 0.9 — surfaces the "one dead seed per cell" story)
        cvals = [r["best_completion"] for r in recs if "best_completion" in r]
        agg["completion_best_seed"] = float(np.max(cvals)) if cvals else float("nan")
        agg["completion_n_ge_090"] = int(sum(1 for c in cvals if c >= 0.9))
        stts = [r["steps_to_threshold"] for r in recs if r.get("steps_to_threshold")]
        agg["steps_to_threshold"] = float(np.mean(stts)) if stts else None
        out[key] = agg
    return out


# ----- cell formatters -----------------------------------------------------------
def _pm(mean, ci, scale=1.0, digits=2):
    if mean != mean:
        return "---"
    m, c = mean * scale, ci * scale
    return f"{m:.{digits}f}{{\\scriptsize$\\pm${c:.{digits}f}}}"


def _deg(mean, ci):  # radians -> degrees
    return _pm(mean, ci, scale=180.0 / math.pi, digits=1)


def _pct(mean, ci):
    return _pm(mean, ci, scale=100.0, digits=1)


def _steps(v):
    return "---" if not v else f"{v/1000:.0f}k"


# ----- table writers -------------------------------------------------------------
_PREAMBLE = ("% Auto-generated by scripts/export_thesis_results.py "
             "(CuPy Stage-1 ablation study)\n"
             "% Cells are mean $\\pm$ 95% CI over seeds; best-checkpoint policy.\n")


def _table(caption, label, header_cells, rows):
    ncol = len(header_cells)
    lines = [
        "\\begin{table}[H]", "\\centering", f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\resizebox{\\ifdim\\width>\\linewidth \\linewidth\\else \\width\\fi}{!}{%",
        "\\begin{tabular}{l" + "c" * (ncol - 1) + "}", "\\toprule",
        " & ".join(header_cells) + " \\\\", "\\midrule",
    ]
    lines += [" & ".join(r) + " \\\\" for r in rows]
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    return "\n".join(lines)


def reward_table(agg, direction, algo):
    """Reward-shaping ablation at a fixed algorithm (rows = reward modes)."""
    hdr = ["Reward", "\\makecell{CTE\\\\Trailer\\\\(m)}", "\\makecell{Max $|\\gamma|$\\\\($^\\circ$)}",
           "\\makecell{Completion\\\\(\\%)}", "\\makecell{Best\\\\seed\\\\(\\%)}",
           "\\makecell{Seeds\\\\$\\geq$0.9}", "\\makecell{Jackknife\\\\(\\%)}"]
    rows = []
    for reward in REWARD_ORDER:
        a = agg.get((algo, direction, reward))
        if not a:
            continue
        rows.append([REWARD_NAME.get(reward, reward),
                     _pm(*a["trailer_cte"]), _deg(*a["max_hitch"]),
                     _pct(*a["completion"]),
                     f"{a['completion_best_seed'] * 100:.1f}",
                     f"{a['completion_n_ge_090']}/{a['n_seeds']}",
                     _pct(*a["jackknife"])])
    cap = (f"{direction.capitalize()} lane-following: reward-shaping ablation "
           f"({ALGO_NAME.get(algo, algo)}, multi-seed; mean $\\pm$ CI, best-seed, robustness).")
    return _table(cap, f"tab:reward_ablation_{direction}", hdr, rows)


def algorithm_table(agg, direction, reward):
    """Algorithm comparison at a fixed reward (rows = algorithms)."""
    hdr = ["Algorithm", "\\makecell{CTE\\\\Trailer\\\\(m)}", "\\makecell{Max $|\\gamma|$\\\\($^\\circ$)}",
           "\\makecell{Completion\\\\(\\%)}", "\\makecell{Best\\\\seed\\\\(\\%)}",
           "\\makecell{Seeds\\\\$\\geq$0.9}", "\\makecell{Steps to\\\\threshold}"]
    rows = []
    for algo in ALGO_ORDER:
        a = agg.get((algo, direction, reward))
        if not a:
            continue
        rows.append([ALGO_NAME.get(algo, algo),
                     _pm(*a["trailer_cte"]), _deg(*a["max_hitch"]),
                     _pct(*a["completion"]),
                     f"{a['completion_best_seed'] * 100:.1f}",
                     f"{a['completion_n_ge_090']}/{a['n_seeds']}",
                     _steps(a["steps_to_threshold"])])
    cap = (f"{direction.capitalize()} lane-following: RL algorithm comparison "
           f"({REWARD_NAME.get(reward, reward)} reward, multi-seed; mean $\\pm$ CI, best-seed, robustness).")
    return _table(cap, f"tab:algorithm_comparison_{direction}", hdr, rows)


# ----- best selection ------------------------------------------------------------
def best_by_completion(agg, direction, axis, fixed_key, fixed_val):
    """Pick the value of `axis` maximising mean completion (tie-break: lower CTE)."""
    best, key = None, None
    for (a, d, rw), v in agg.items():
        if d != direction:
            continue
        sel = {"algo": a, "reward": rw}
        if sel[fixed_key] != fixed_val:
            continue
        cand = sel[axis]
        score = (round(v["completion"][0], 3), -v["trailer_cte"][0])
        if best is None or score > best:
            best, key = score, cand
    return key


# ----- learning-curve figures ----------------------------------------------------
def curve_figures(outdir, export_dir, algo, reward):
    """Reward-ablation learning curves per direction (completion vs timesteps)."""
    curves_path = os.path.join(outdir, "curves.csv")
    if not os.path.exists(curves_path):
        return []
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    with open(curves_path) as f:
        rows = list(csv.DictReader(f))
    made = []
    for direction in sorted({r["direction"] for r in rows}):
        # mean over seeds, per reward, for the fixed algorithm
        series = defaultdict(lambda: defaultdict(list))  # reward -> t -> [completion]
        for r in rows:
            if r["direction"] != direction or r["algo"] != algo:
                continue
            try:
                t = int(float(r["timesteps"])); c = float(r["completion"])
            except (TypeError, ValueError):
                continue
            series[r["reward"]][t].append(c)
        if not series:
            continue
        fig, ax = plt.subplots(figsize=(5, 3.2))
        for reward_mode in REWARD_ORDER:
            if reward_mode not in series:
                continue
            ts = sorted(series[reward_mode])
            ys = [float(np.mean(series[reward_mode][t])) for t in ts]
            ax.plot(ts, ys, marker="o", ms=3, label=REWARD_NAME.get(reward_mode, reward_mode))
        ax.set_xlabel("Timesteps"); ax.set_ylabel("Completion rate")
        ax.set_ylim(-0.02, 1.02); ax.set_title(f"{direction.capitalize()} ({ALGO_NAME.get(algo, algo)})")
        ax.legend(fontsize=7); ax.grid(alpha=0.3); fig.tight_layout()
        out = os.path.join(export_dir, f"{direction}_reward_ablation.pdf")
        fig.savefig(out); plt.close(fig); made.append(os.path.basename(out))
    return made


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--outdir", default="results_stage1_v3")
    ap.add_argument("--algo", default=None, help="fix reward table to this algo (default: best by completion)")
    ap.add_argument("--reward", default=None, help="fix algorithm table to this reward (default: best)")
    ap.add_argument("--thesis_tables", default=None,
                    help="optional: also copy .tex into this dir (e.g. e2e_rl/thesis/tables). "
                         "Off by default so the thesis is never touched implicitly.")
    args = ap.parse_args()

    runs = load_runs(args.outdir)
    if not runs:
        print(f"# no completed runs in {args.outdir}/manifest.jsonl yet"); return
    agg = aggregate(runs, ["algo", "direction", "reward"])
    directions = sorted({r["direction"] for r in runs})
    export_dir = os.path.join(args.outdir, "thesis_export")
    os.makedirs(export_dir, exist_ok=True)

    written, figs = [], []
    readme = ["Thesis import — Stage-1 GPU ablation study", "=" * 44, "",
              f"Source: {os.path.abspath(args.outdir)}  ({len(runs)} completed runs)", ""]

    for direction in directions:
        # reward table: fix the winning algorithm (or --algo)
        algo = args.algo or best_by_completion(agg, direction, "algo", "reward",
                                               args.reward or "multiplicative")
        # algorithm table: fix the winning reward (or --reward)
        reward = args.reward or best_by_completion(agg, direction, "reward", "algo", algo)
        for name, tex in [(f"reward_ablation_{direction}", reward_table(agg, direction, algo)),
                          (f"algorithm_comparison_{direction}", algorithm_table(agg, direction, reward))]:
            p = os.path.join(export_dir, name + ".tex")
            with open(p, "w") as f:
                f.write(_PREAMBLE + "\n" + tex + "\n")
            written.append(p)
        readme.append(f"[{direction}] reward table @ algo={algo}   |   algorithm table @ reward={reward}")
        figs += curve_figures(args.outdir, export_dir, algo, reward)

    readme += ["", "To import into the thesis (from thesis/ dir), \\input the tables, e.g.:",
               "    \\input{tables/reward_ablation_forward.tex}",
               "    \\input{tables/algorithm_comparison_forward.tex}", "",
               "Copy the generated files in with (run yourself when ready):",
               f"    cp {export_dir}/*.tex  <thesis>/tables/",
               f"    cp {export_dir}/*.pdf  <thesis>/figures/"]
    with open(os.path.join(export_dir, "_README.txt"), "w") as f:
        f.write("\n".join(readme) + "\n")

    if args.thesis_tables:
        import shutil
        os.makedirs(args.thesis_tables, exist_ok=True)
        for p in written:
            shutil.copy(p, args.thesis_tables)
        print(f"# copied {len(written)} tables into {args.thesis_tables}")

    print(f"# wrote {len(written)} tables + {len(figs)} figures -> {export_dir}")
    for p in written:
        print(f"    {os.path.basename(p)}")
    for p in figs:
        print(f"    {p}")


if __name__ == "__main__":
    main()
