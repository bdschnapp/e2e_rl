def figure_reverse_crash_gate(models):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    dyn = models["hp_reverse_avoidance_d_win_dyn_final_s0"]
    xs = [(b["lo"] + b["hi"]) / 2 for b in dyn["buckets"]]
    crash = [b["crash"] * 100 for b in dyn["buckets"]]
    comp = [b["complete"] * 100 for b in dyn["buckets"]]
    stop = [b["stop"] * 100 for b in dyn["buckets"]]
    fig, ax = plt.subplots(figsize=(6.0, 3.8))
    ax.plot(xs, comp, marker="o", ms=3, lw=1.6, label="complete")
    ax.plot(xs, stop, marker="s", ms=3, lw=1.6, label="stop")
    ax.plot(xs, crash, marker="^", ms=3, lw=1.6, label="crash")
    ax.axvline(0.5, color="gray", ls="--", lw=1.0)
    ax.set_xlabel("Maximum dynamic difficulty")
    ax.set_ylabel("Outcome rate (%)")
    ax.set_title("Reverse obstacle maneuvering, outcome by dynamic difficulty")
    ax.set_ylim(-3, 103)
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    out = FIGURES_DIR / "reverse_obstacle_gate.pdf"
    fig.savefig(out)
    plt.close(fig)
    print(f"wrote {out.relative_to(THESIS_DIR)}")


