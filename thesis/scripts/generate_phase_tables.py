def _plot_curves(curve_rows, direction, group_field, group_values, group_labels,
                 fixed, out_name, title):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    # Aggregate completion across seeds per (group, timestep).
    from collections import defaultdict
    series = {g: defaultdict(list) for g in group_values}
    for r in curve_rows:
        if r["direction"] != direction:
            continue
        if any(r[k] != v for k, v in fixed.items()):
            continue
        g = r[group_field]
        if g not in series:
            continue
        t = int(float(r["timesteps"]))
        c = fnum(r["completion"])
        if c is not None:
            series[g][t].append(c)

    fig, ax = plt.subplots(figsize=(6.0, 3.8))
    plotted = False
    for g in group_values:
        pts = sorted(series[g].items())
        if not pts:
            continue
        xs = [t / 1000.0 for t, _ in pts]
        ys = [sum(v) / len(v) * 100.0 for _, v in pts]
        ax.plot(xs, ys, marker="o", markersize=3, linewidth=1.6, label=group_labels[g])
        plotted = True
    if not plotted:
        plt.close(fig)
        return
    ax.set_xlabel("Training steps (thousands)")
    ax.set_ylabel("Completion (\\%)" if False else "Completion (%)")
    ax.set_title(title)
    ax.set_ylim(-3, 103)
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=8, loc="lower right")
    fig.tight_layout()
    out = FIGURES_DIR / out_name
    fig.savefig(out)
    plt.close(fig)
    print(f"wrote {out.relative_to(THESIS_DIR)}")


