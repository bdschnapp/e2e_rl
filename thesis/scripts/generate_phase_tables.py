def read_rows(path: Path) -> list[dict[str, str]]:
    """Read a CSV, skipping any leading or interleaved '#' comment lines."""
    with path.open(newline="") as f:
        rows = [ln for ln in f if not ln.lstrip().startswith("#")]
    return list(csv.DictReader(rows))


def key(row: dict[str, str], *fields: str) -> tuple[str, ...]:
    return tuple(row[f] for f in fields)


def fnum(value: str | None) -> float | None:
    if value is None or value == "" or value == "nan":
        return None
    try:
        return float(value)
    except ValueError:
        return None


def pct(mean: float | None, ci: float | None, decimals: int = 1, bold: bool = False) -> str:
    """Completion rendered as a percentage with a small +/- CI, or --- if absent."""
    if mean is None:
        return "---"
    m = mean * 100.0
    body = f"{m:.{decimals}f}"
    if ci is not None:
        body += f"{{\\scriptsize$\\pm${ci * 100.0:.{decimals}f}}}"
    return f"\\textbf{{{body}}}" if bold else body


def num(value: float | None, decimals: int = 3) -> str:
    return "---" if value is None else f"{value:.{decimals}f}"


def deg(value: float | None, decimals: int = 1) -> str:
    return "---" if value is None else f"{value * RAD2DEG:.{decimals}f}"


def write(path: Path, body: str) -> None:
    path.write_text(AUTO_HEADER + "\n" + body)
    print(f"wrote {path.relative_to(THESIS_DIR)}")


