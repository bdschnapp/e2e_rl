def parse_multiseed_analysis(path):
    """Parse final_multiseed_analysis.txt into {model_name: {...}}."""
    models = {}
    cur = None
    for line in path.read_text().splitlines():
        m = re.match(r"### MODEL (\S+)\s+\(dir=(\w+) mild=(\w+) dynamic_diff=(\w+)\)", line)
        if m:
            cur = {"name": m.group(1), "dir": m.group(2), "dynamic": m.group(4) == "True",
                   "overall": {}, "buckets": []}
            models[m.group(1)] = cur
            continue
        if cur is None:
            continue
        mo = re.match(r"OVERALL n=(\d+)\s+complete=([\d.]+)\s+stop=([\d.]+)\s+crash=([\d.]+)", line)
        if mo:
            cur["overall"] = {"n": int(mo.group(1)), "complete": float(mo.group(2)),
                              "stop": float(mo.group(3)), "crash": float(mo.group(4))}
            continue
        mb = re.match(r"\s*\[([\d.]+),([\d.]+)\)\s+(\d+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+|nan)", line)
        if mb:
            cur["buckets"].append({"lo": float(mb.group(1)), "hi": float(mb.group(2)),
                                   "n": int(mb.group(3)), "complete": float(mb.group(4)),
                                   "stop": float(mb.group(5)), "crash": float(mb.group(6)),
                                   "hitch": mb.group(7)})
            continue
        mc = re.match(r"collision geometry: tractor-clip=([\d.]+) trailer-clip=([\d.]+)", line)
        if mc:
            cur["tractor_clip"] = float(mc.group(1))
            cur["trailer_clip"] = float(mc.group(2))
    return models


def parse_vision(path):
    """Parse final_multiseed_vision.txt -> {reverse:{r2,safe,crash}, forward:{...}}."""
    out = {"reverse": {"r2": {}}, "forward": {"r2": {}}}
    section = None
    for line in path.read_text().splitlines():
        if "REVERSE encoder" in line:
            section = "reverse"
        elif "FORWARD encoder" in line:
            section = "forward"
        if section is None:
            continue
        m = re.match(r"\s+(\w+)\s+R2=\+?([\d.\-]+)", line)
        if m:
            out[section]["r2"][m.group(1)] = float(m.group(2))
        ms = re.search(r"SAFE.*=\s*([\d.]+)\s+crash\s*=\s*([\d.]+)", line)
        if ms:
            out[section]["safe"] = float(ms.group(1))
            out[section]["crash"] = float(ms.group(2))
    return out


