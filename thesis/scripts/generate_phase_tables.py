def parse_classical_log(path: Path):
    """Parse the simple '[forward]/[reverse]' safe-pool baseline log."""
    result = {"forward": {}, "reverse": {}}
    section = None
    for line in path.read_text().splitlines():
        s = line.strip()
        if s == "[forward]":
            section = "forward"
        elif s == "[reverse]":
            section = "reverse"
        elif section and "compl=" in s:
            name = s.split()[0]
            parts = {kv.split("=")[0]: float(kv.split("=")[1]) for kv in s.split() if "=" in kv}
            result[section][name] = parts
    return result


