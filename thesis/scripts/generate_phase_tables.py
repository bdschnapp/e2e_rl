def algo_reward_matrix(rows, direction, rewards, champion=None):
    idx = {key(r, "algo", "reward"): r for r in rows if r["direction"] == direction}
    header_cols = " & ".join(f"\\makecell{{{REWARD_LABEL[r]}}}" for r in rewards)
    lines = [
        "\\begin{table}[H]",
        "\\centering",
        f"\\caption{{{direction.capitalize()} lane-following, best-checkpoint completion "
        "rate (\\%) for every algorithm and reward combination on the engineered state "
        "observation. Cells are the mean over three seeds with a 95\\% confidence "
        "interval. The chosen recipe is highlighted.}",
        f"\\label{{tab:algorithm_comparison_{direction}}}",
        "\\resizebox{\\ifdim\\width>\\linewidth \\linewidth\\else \\width\\fi}{!}{%",
        "\\begin{tabular}{l" + "c" * len(rewards) + "}",
        "\\toprule",
        f"Algorithm & {header_cols} \\\\",
        "\\midrule",
    ]
    for algo in ALGO_ORDER:
        cells = []
        for reward in rewards:
            r = idx.get((algo, reward))
            if r is None:
                cells.append("---")
                continue
            is_champ = champion == (algo, reward, direction)
            cells.append(pct(fnum(r["completion_mean"]), fnum(r["completion_ci95"]), bold=is_champ))
        lines.append(f"{ALGO_LABEL[algo]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]
    return "\n".join(lines) + "\n"


